"""Keep doc/tags and doc/tags-cn byte-equivalent to a fresh Neovim :helptags run.

Neovim resolves a help tag only through a tags file whose entry points at an
existing help file. A stale or hand-edited tags file makes translated help
silently unreachable, so this test regenerates both files into a temp dir using
Neovim itself and compares the entry sets with the committed ones.

Regeneration equality is only meaningful for the Neovim that generated them:
both files ship from the pinned 0.12.6 release, so "the index equals *that*
generator's output" is a pinned statement. It is not a claim that another
Neovim indexes fewer tags -- 0.11.5 regenerates both files byte for byte
identically, including E767, "[q" and "uv.pipe_chmod()". What every version
still checks is that the shipped index resolves through :help (13 sampled tags,
including those special-character ones) and that each index line carries the
canonical search pattern (03_help_parity_rules_spec.lua).
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(os.environ['NVIM_ZH_ROOT']).resolve()
DOC = ROOT / 'doc'
NVIM = os.environ.get('NVIM_BIN', 'nvim')
PINNED_ONLY = 'doc/tags and doc/tags-cn are generated by the pinned Neovim 0.12.6'

sys.path.insert(0, str(Path(__file__).resolve().parent))
import help_parity as parity  # noqa: E402


def _pinned() -> bool:
    out = subprocess.run(
        [NVIM, '--version'], capture_output=True, text=True, timeout=60,
        env={**os.environ, 'XDG_STATE_HOME': os.environ.get('XDG_STATE_HOME', tempfile.gettempdir())})
    if out.returncode != 0:
        raise RuntimeError(f'Neovim version probe exited {out.returncode}: {out.stderr.strip()}')
    match = re.search(r'^NVIM v(\S+)', out.stdout, re.M)
    if not match:
        raise RuntimeError(f'Neovim version probe returned unrecognised output: {out.stdout!r}')
    return match.group(1) == '0.12.6'


def _helptags(doc_dir: Path) -> None:
    state = Path(tempfile.mkdtemp(prefix='nvim-zh-help-state-'))
    try:
        # "-c ... -c qa!" (not "--cmd") so Neovim actually exits after tagging.
        subprocess.run(
            [NVIM, '--headless', '-u', 'NONE', '-c', f'helptags {doc_dir}', '-c', 'qa!'],
            check=True,
            capture_output=True,
            timeout=60,
            env={**os.environ, 'XDG_STATE_HOME': str(state)},
        )
    finally:
        shutil.rmtree(state, ignore_errors=True)


def _entries(path: Path) -> set[tuple[str, str]]:
    rows: set[tuple[str, str]] = set()
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line:
            continue
        parts = line.split('\t')
        if len(parts) != 3:
            raise AssertionError(f'{path.name}: malformed tags line {line!r}')
        tag, filename, pattern = parts
        # :helptags writes a search pattern with the regex-special characters
        # escaped: backslashes are doubled (a tag like "t_CTRL-\_CTRL-O" becomes
        # "/*t_CTRL-\\_CTRL-O*") and a "/" inside a tag is escaped as "\/"
        # (cmdline.txt documents the "/_<Tab>" tag, which becomes "/*\/_<Tab>*").
        expected = '/*' + tag.replace('\\', '\\\\').replace('/', '\\/') + '*'
        if pattern != expected:
            raise AssertionError(f'{path.name}: {tag} has non-canonical pattern {pattern!r}')
        if not (path.parent / filename).is_file():
            raise AssertionError(f'{path.name}: {tag} points at missing {filename}')
        rows.add((tag, filename))
    return rows


class HelpTagsTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix='nvim-zh-help-'))
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def _regenerate(self, suffix: str, tags_name: str) -> set[tuple[str, str]]:
        doc = self.tmp / tags_name
        doc.mkdir()
        sources = sorted(DOC.glob(f'*{suffix}'))
        self.assertTrue(sources, f'no {suffix} help files to check')
        for source in sources:
            shutil.copy2(source, doc / source.name)
        _helptags(doc)
        generated = doc / tags_name
        self.assertTrue(generated.is_file(), f'{tags_name} was not generated')
        return _entries(generated)

    @unittest.skipUnless(_pinned(), PINNED_ONLY)
    def test_tags_cn_matches_neovim_generation(self):
        self.assertEqual(_entries(DOC / 'tags-cn'), self._regenerate('.cnx', 'tags-cn'),
                         'doc/tags-cn is stale or hand-edited')

    @unittest.skipUnless(_pinned(), PINNED_ONLY)
    def test_tags_matches_neovim_generation(self):
        self.assertEqual(_entries(DOC / 'tags'), self._regenerate('.txt', 'tags'),
                         'doc/tags is stale or hand-edited')

    def test_first_lines_share_one_encoding_class(self) -> None:
        """Neovim 0.11 decides a help file's encoding from its FIRST line.

        src/nvim/help.c helptags_one(): a non-ASCII byte in the first line means
        utf-8, an ASCII-only first line means latin1, and a directory that mixes
        the two aborts the whole language with E670 *before writing any tag* —
        the shipped doc/tags-cn (10798 entries) is rewritten as an empty file
        while :helptags still exits 0. 0.12 removed the check entirely, so a
        mixed corpus breaks only 0.10/0.11. Keep every doc/*.cnx first line
        ASCII-only, exactly like the other 129 files (the upstream header line,
        with the Chinese title on a following line).
        """
        offenders = [path.name for path in sorted(DOC.glob('*.cnx'))
                     if any(byte >= 0x80 for byte in path.read_bytes().split(b'\n', 1)[0])]
        self.assertEqual(offenders, [],
                         'non-ASCII first line would abort :helptags on 0.11: '
                         + ', '.join(offenders))

    def test_helptags_regeneration_is_not_destructive(self) -> None:
        """Regenerating tags-cn must never truncate it to nothing.

        E670 aborts the language but leaves :helptags with exit status 0, so
        nothing in the exit code reveals it; this runs on every version, pinned
        or not, and is the regression test for
        test_first_lines_share_one_encoding_class.
        """
        doc = self.tmp / 'regen'
        doc.mkdir()
        sources = sorted(DOC.glob('*.cnx'))
        self.assertTrue(sources, 'no doc/*.cnx to regenerate from')
        for source in sources:
            shutil.copy2(source, doc / source.name)
        state = Path(tempfile.mkdtemp(prefix='nvim-zh-help-state-'))
        self.addCleanup(shutil.rmtree, state, True)
        result = subprocess.run(
            [NVIM, '--headless', '-u', 'NONE', '-c', f'helptags {doc}', '-c', 'qa!'],
            capture_output=True, text=True, timeout=120,
            env={**os.environ, 'XDG_STATE_HOME': str(state)})
        self.assertEqual(result.returncode, 0, result.stderr)
        for token in ('E670', 'E151', 'E152', 'E153', 'E154'):
            self.assertNotIn(token, result.stderr,
                             f'{token} while regenerating tags-cn: {result.stderr}')
        generated = doc / 'tags-cn'
        self.assertTrue(generated.is_file(), 'tags-cn was not generated')
        self.assertGreaterEqual(len(_entries(generated)), 1000, 'tags-cn was truncated')

    def test_shipped_tags_are_internally_consistent(self) -> None:
        """tags-cn/tags and the shipped help files must agree in both directions.

        Regeneration equality proves the index matches the *pinned* generator,
        but that comparison is pinned-only. This invariant is repository
        internal, so it runs everywhere: a tag definition deleted from a .cnx
        (leaving a stale index entry) and an index entry pointing at a file that
        no longer defines it are both caught off-pin.
        """
        for tags_name, suffix in (('tags-cn', '*.cnx'), ('tags', '*.txt')):
            allowed = {path.name for path in DOC.glob(suffix)}
            self.assertTrue(allowed, f'no doc/{suffix} files')
            entries: dict[str, str] = {}
            for line in (DOC / tags_name).read_text(encoding='utf-8').splitlines():
                if not line or line.startswith('!_TAG_'):
                    continue  # "!_TAG_FILE_ENCODING ..." and other meta lines
                tag, filename, _pattern = line.split('\t')
                self.assertNotIn(tag, entries, f'{tags_name}: duplicate tag {tag}')
                entries[tag] = filename
            defined = {name: set(parity.tags((DOC / name).read_text(encoding='utf-8')))
                       for name in sorted(allowed)}
            for tag, filename in entries.items():
                self.assertIn(filename, allowed, f'{tags_name}: {tag} points outside {suffix}')
                self.assertIn(tag, defined[filename],
                              f'{tags_name}: {tag} is not defined in {filename} any more')
            for filename, names in defined.items():
                for tag in sorted(names):
                    self.assertEqual(entries.get(tag), filename,
                                     f'{tags_name}: {filename} defines {tag} but the index says '
                                     f'{entries.get(tag)!r}')

    def test_helptags_skips_tags_inside_example_blocks(self):
        """Pin the :helptags rule the parity scanner has to mirror.

        helphelp.txt shows the help-file header format inside an example block,
        so its "*plugin_name.txt*" is example text, not a tag. Neovim's
        :helptags does not index it, and the Help tag scanner must agree:
        otherwise it demands a tags-cn entry that can never exist. This test
        pins Neovim's behaviour itself, so an upstream change surfaces here
        instead of inside a translation.
        """
        doc = self.tmp / 'rule'
        doc.mkdir()
        (doc / 'rule.cnx').write_text(
            'format: >\n'
            '\n'
            '\t*inside_example.txt*\t{description}\n'
            '\n'
            '*real_tag*\tsome text\n',
            encoding='utf-8',
        )
        _helptags(doc)
        entries = _entries(doc / 'tags-cn')
        self.assertIn(('real_tag', 'rule.cnx'), entries)
        self.assertNotIn(('inside_example.txt', 'rule.cnx'), entries,
                         ':helptags started indexing tags inside example blocks')


# Tags the shipped files must resolve on whatever Neovim runs the suite. Half of
# them name characters 0.11.5's :helptags refuses to index itself, which is why
# the shipped (0.12.6-generated) files have to be checked by *lookup* and not
# only by regeneration. "credits" has no Chinese copy and must fall back.
SAMPLE_TAGS = (
    ('hl-ErrorMsg', 'syntax.cnx'),
    ('E767', 'vimfn.cnx'),
    ('quote:', 'change.cnx'),
    ('-u', 'starting.cnx'),
    ('[q', 'quickfix.cnx'),
    ('treesitter-predicate-any-eq?', 'treesitter.cnx'),
    ('uv.pipe_chmod()', 'luvref.cnx'),
    ('lua-guide', 'lua-guide.cnx'),
    ('nvim-zh', 'nvim-zh.cnx'),
    ('ft_hare', 'ft_hare.cnx'),
    ('usr_01', 'usr_01.cnx'),
    ('E5113', 'message.cnx'),
    ('credits', 'credits.txt'),
)


class ShippedTagsResolveTests(unittest.TestCase):
    def test_shipped_tags_resolve_through_help(self):
        driver = Path(tempfile.mkdtemp(prefix='nvim-zh-help-resolve-'))
        self.addCleanup(shutil.rmtree, driver, True)
        cases = '\n'.join(
            '  { %s, %s },' % (json.dumps(tag), json.dumps(expected))
            for tag, expected in SAMPLE_TAGS)
        script = driver / 'resolve.lua'
        result = driver / 'result.txt'
        script.write_text(
            'vim.cmd("set runtimepath^=" .. vim.env.NVIM_ZH_ROOT)\n'
            'vim.cmd("runtime! plugin/nvim-zh.lua")\n'
            'require("nvim-zh").setup({ modules = { core = { enabled = false } } })\n'
            'local cases = {\n' + cases + '\n}\n'
            'local rows = {}\n'
            'for _, row in ipairs(cases) do\n'
            '  local ok = pcall(vim.cmd, "help " .. row[1])\n'
            '  local got = vim.fs.basename(vim.api.nvim_buf_get_name(0))\n'
            '  table.insert(rows, ("%s\\t%s\\t%s"):format(row[1], got, ok and "ok" or "error"))\n'
            'end\n'
            'io.open(vim.env.PROBE_OUT, "w"):write(table.concat(rows, "\\n") .. "\\n")\n',
            encoding='utf-8')
        state = driver / 'state'
        state.mkdir()
        subprocess.run(
            [NVIM, '--headless', '-u', 'NONE', '-l', str(script)],
            check=True, capture_output=True, timeout=120,
            env={**os.environ, 'NVIM_ZH_ROOT': str(ROOT), 'PROBE_OUT': str(result),
                 'XDG_STATE_HOME': str(state)})
        resolved = {}
        for line in result.read_text(encoding='utf-8').splitlines():
            tag, filename, status = line.split('\t')
            resolved[tag] = filename if status == 'ok' else f'<{status}>'
        for tag, expected in SAMPLE_TAGS:
            self.assertEqual(resolved.get(tag), expected,
                             f':help {tag} did not reach {expected} on this Neovim')


if __name__ == '__main__':
    unittest.main(verbosity=1)
