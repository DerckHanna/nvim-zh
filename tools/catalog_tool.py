#!/usr/bin/env python3
"""Deterministic PO validation and PO-to-Lua catalog generation."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import stat
import sys
import tempfile
import tomllib
import urllib.request
from collections import Counter
from collections.abc import Callable
from pathlib import Path

GENERATED_HEADER = '-- Generated by tools/catalog_tool.py from PO; do not edit.'
PRINTF = re.compile(r'%([-+ #0]*)(\d*)(\.?\d*)([diufeEgGxXoscq])')
NAMED = re.compile(r'\{([A-Za-z_][A-Za-z0-9_]*)\}')
PROTECTED_PATTERNS = (
    re.compile(r'`[^`\n]+`'),
    re.compile(r'<[A-Z][A-Za-z0-9-]*(?:-[A-Za-z0-9]+)*>'),
    re.compile(r':[A-Za-z][A-Za-z0-9_-]*'),
    re.compile(r'\bvim(?:\.[A-Za-z_][A-Za-z0-9_]*)+(?:\(\))?'),
    re.compile(r'(?<![\w:])/(?:[^/\s]+/)*[^/\s]+'),
    re.compile(r'\b[A-Za-z]:\\[^\s]+'),
    re.compile(r'\b[A-Za-z][A-Za-z0-9]*_[A-Za-z0-9_]+\b'),
    re.compile(r"'[a-z][a-z0-9_-]*'"),
)


class CatalogError(ValueError):
    pass


def _atomic_write(path: Path, write: Callable[[Path], None]) -> None:
    """Publish one complete file without exposing a partial target."""
    fd, temporary_name = tempfile.mkstemp(prefix=f'.{path.name}.', suffix='.tmp', dir=path.parent)
    os.close(fd)
    temporary = Path(temporary_name)
    try:
        write(temporary)
        with temporary.open('rb') as stream:
            os.fsync(stream.fileno())
        try:
            mode = stat.S_IMODE(path.stat().st_mode)
        except FileNotFoundError:
            mode = 0o644
        temporary.chmod(mode)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def atomic_write_text(path: Path, text: str) -> None:
    """Write UTF-8/LF text atomically, preserving an existing file's mode."""
    _atomic_write(path, lambda temporary: temporary.write_text(
        text, encoding='utf-8', newline='\n'))


def atomic_write_bytes(path: Path, data: bytes) -> None:
    """Write bytes atomically, preserving an existing file's mode."""
    _atomic_write(path, lambda temporary: temporary.write_bytes(data))


def _quoted(text: str, path: Path, line: int) -> str:
    if not text.startswith('"'):
        raise CatalogError(f'{path}:{line}: PO string must be double-quoted')
    try:
        value = ast.literal_eval(text)
    except (SyntaxError, ValueError) as exc:
        raise CatalogError(f'{path}:{line}: malformed PO string') from exc
    if not isinstance(value, str):
        raise CatalogError(f'{path}:{line}: malformed PO string')
    return value


def parse_po(path: Path) -> tuple[list[dict], dict[str, str]]:
    try:
        text = path.read_bytes().decode('utf-8')
    except UnicodeDecodeError as exc:
        raise CatalogError(f'{path}: invalid UTF-8') from exc
    entries: list[dict] = []
    current: dict | None = None
    active: str | None = None

    def finish() -> None:
        nonlocal current, active
        if current is not None:
            if 'msgid' not in current or 'msgstr' not in current:
                raise CatalogError(f'{path}: incomplete PO entry')
            entries.append(current)
        current = None
        active = None

    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        if line.startswith('#'):
            if current is not None and 'msgstr' in current:
                finish()
            if current is None:
                current = {'references': [], 'flags': []}
            if line.startswith('#:'):
                current['references'].extend(line[2:].split())
            elif line.startswith('#,'):
                current['flags'].extend(flag.strip() for flag in line[2:].split(','))
            continue
        directive = re.match(r'^(msgctxt|msgid|msgstr)\s+(.+)$', line)
        if directive:
            keyword, value = directive.groups()
            if keyword in ('msgctxt', 'msgid') and current is not None and 'msgid' in current:
                finish()
            if current is None:
                current = {'references': [], 'flags': []}
            if keyword in current:
                raise CatalogError(f'{path}:{number}: duplicate {keyword}')
            current[keyword] = _quoted(value, path, number)
            active = keyword
            continue
        if line.startswith('msgid_plural') or re.match(r'^msgstr\[\d+\]', line):
            raise CatalogError(f'{path}:{number}: plural entries are not supported by this zh_CN builder')
        if line.startswith('"') and current is not None and active is not None:
            current[active] += _quoted(line, path, number)
            continue
        raise CatalogError(f'{path}:{number}: malformed PO syntax')
    finish()

    headers: dict[str, str] = {}
    result: list[dict] = []
    for entry in entries:
        if entry['msgid'] == '' and not entry.get('msgctxt'):
            for line in entry['msgstr'].splitlines():
                if ':' in line:
                    key, value = line.split(':', 1)
                    headers[key.strip()] = value.strip()
        else:
            result.append(entry)
    charset = headers.get('Content-Type', '')
    if charset and not re.search(r'charset=UTF-8(?:\s|$)', charset, re.I):
        raise CatalogError(f'{path}: PO Content-Type must use UTF-8')
    return result, headers


def placeholders(text: str, location: str) -> tuple[str | None, list[str]]:
    named = NAMED.findall(text)
    printf: list[str] = []
    index = 0
    while index < len(text):
        if text[index] != '%':
            index += 1
            continue
        if text[index:index + 2] == '%%':
            index += 2
            continue
        match = PRINTF.match(text, index)
        if match:
            printf.append(match.group(4))
            index = match.end()
            continue
        following = text[index + 1:index + 4]
        if re.match(r'^(?:\*|\d+\$|[-+ #0]*\d*(?:\.\d+)?[A-Za-z])', following):
            raise CatalogError(f'{location}: unsupported or abnormal printf placeholder near {text[index:index + 8]!r}')
        index += 1
    if named and printf:
        raise CatalogError(f'{location}: named and printf placeholders cannot be mixed')
    return ('named' if named else 'printf' if printf else None), named or printf


def check_entry(entry: dict, path: Path, terms: list[dict]) -> None:
    context = entry.get('msgctxt', '')
    msgid, msgstr = entry['msgid'], entry['msgstr']
    location = f'{path}: {context!r}/{msgid!r}'
    if not msgstr:
        raise CatalogError(f'{location}: empty translation')
    if 'fuzzy' in entry.get('flags', []):
        raise CatalogError(f'{location}: fuzzy translation must be reviewed')
    source_kind, source_tokens = placeholders(msgid, location)
    target_kind, target_tokens = placeholders(msgstr, location)
    if source_kind != target_kind:
        raise CatalogError(f'{location}: placeholder kind mismatch')
    if source_kind == 'printf' and source_tokens != target_tokens:
        raise CatalogError(f'{location}: non-positional printf order/type must remain identical')
    if source_kind == 'named' and Counter(source_tokens) != Counter(target_tokens):
        raise CatalogError(f'{location}: named placeholder mismatch')
    for pattern in PROTECTED_PATTERNS:
        if Counter(pattern.findall(msgid)) != Counter(pattern.findall(msgstr)):
            raise CatalogError(f'{location}: protected command, path, option, or code span changed')
    for term in terms:
        source = term['source']
        if term.get('domain') not in (None, path.stem) or term.get('context') not in (None, context):
            continue
        present = re.search(rf'(?<![A-Za-z0-9_]){re.escape(source)}(?![A-Za-z0-9_])', msgid)
        # Preserve the exact technical spelling for singular capitalized terms.
        # Also reject forbidden translations for lowercase/plural source forms;
        # otherwise "buffers" or "current buffer" silently bypass the glossary.
        inflected = re.search(rf'(?<![A-Za-z0-9_]){re.escape(source)}s?(?![A-Za-z0-9_])',
                              msgid, flags=re.IGNORECASE)
        if term.get('policy') == 'preserve' and present and source not in msgstr:
            raise CatalogError(f'{location}: preserved term {source!r} was translated or removed')
        if not present and not inflected:
            continue
        for forbidden in term.get('forbidden', []):
            if forbidden in msgstr:
                raise CatalogError(f'{location}: forbidden translation {forbidden!r} for {source!r}')


def load_glossary(path: Path | None) -> list[dict]:
    if path is None:
        return []
    if not path.is_file():
        raise CatalogError(f'{path}: glossary file does not exist')
    try:
        data = tomllib.loads(path.read_bytes().decode('utf-8'))
    except OSError as exc:
        raise CatalogError(f'{path}: cannot read glossary: {exc}') from exc
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise CatalogError(f'{path}: invalid UTF-8 TOML glossary') from exc
    terms = data.get('term', [])
    if not isinstance(terms, list):
        raise CatalogError(f'{path}: glossary term must be an array of tables')
    for term in terms:
        if not isinstance(term.get('source'), str) or term.get('policy') not in ('preserve', 'translate'):
            raise CatalogError(f'{path}: each term needs source and preserve/translate policy')
    return terms


def builtin_sources(root: Path) -> dict[str, Path]:
    """Read the data-only BUILTIN_SOURCES table; do not duplicate its domains."""
    source = (root / 'lua/nvim-zh/catalog.lua').read_text(encoding='utf-8')
    table = re.search(r'local BUILTIN_SOURCES = \{(.*?)\n\}', source, re.S)
    if not table:
        raise CatalogError('missing BUILTIN_SOURCES table')
    result = {}
    for line in table[1].strip().splitlines():
        match = re.fullmatch(r"\s*(?:\['([^']+)'\]|(\w+)) = '([^']+)',\s*", line)
        if not match:
            raise CatalogError(f'invalid BUILTIN_SOURCES line: {line}')
        domain, relative = match[1] or match[2], match[3]
        if relative != f'translations/po/zh_CN/{domain}.po' or domain in result:
            raise CatalogError(f'invalid builtin source: {domain}')
        result[domain] = root / relative
    actual = set((root / 'translations/po/zh_CN').glob('*.po'))
    if actual != set(result.values()):
        raise CatalogError('production PO files differ from BUILTIN_SOURCES')
    return result


def check(po_dir: Path, glossary: Path | None = None) -> dict[str, int]:
    if not po_dir.is_dir():
        raise CatalogError(f'{po_dir}: PO directory does not exist')
    files = sorted(po_dir.glob('*.po'), key=lambda path: path.name)
    if not files:
        raise CatalogError(f'{po_dir}: no PO files found')
    terms = load_glossary(glossary)
    count = 0
    for path in files:
        entries, _ = parse_po(path)
        seen: set[tuple[str, str]] = set()
        for entry in entries:
            key = entry.get('msgctxt', ''), entry['msgid']
            if key in seen:
                raise CatalogError(f'{path}: duplicate context/msgid key {key!r}')
            seen.add(key)
            check_entry(entry, path, terms)
            count += 1
    return {'domains': len(files), 'entries': count, 'translated': count}


def lua_quote(value: str) -> str:
    output = ['"']
    for char in value:
        code = ord(char)
        escapes = {'\\': '\\\\', '"': '\\"', '\n': '\\n', '\r': '\\r', '\t': '\\t'}
        if char in escapes:
            output.append(escapes[char])
        elif code < 32 or code == 127:
            output.append(f'\\{code:03d}')
        else:
            output.append(char)
    output.append('"')
    return ''.join(output)


def render_catalog(domain: str, entries: list[dict], headers: dict[str, str], source: str) -> str:
    lines = [
        GENERATED_HEADER,
        'return {',
        '  schema = 1,',
        f'  domain = {lua_quote(domain)},',
        '  locale = "zh_CN",',
        '  metadata = {',
        f'    source = {lua_quote(source)},',
        '    headers = {',
    ]
    for key in sorted(headers):
        lines.append(f'      [{lua_quote(key)}] = {lua_quote(headers[key])},')
    lines.extend(['    },', '  },', '  entries = {'])
    for entry in sorted(entries, key=lambda item: (item.get('msgctxt', ''), item['msgid'])):
        lines.append('    {')
        lines.append(f'      context = {lua_quote(entry.get("msgctxt", ""))},')
        lines.append(f'      msgid = {lua_quote(entry["msgid"])},')
        lines.append(f'      msgstr = {lua_quote(entry["msgstr"])},')
        if entry.get('references'):
            lines.append('      references = {')
            for reference in sorted(entry['references']):
                lines.append(f'        {lua_quote(reference)},')
            lines.append('      },')
        if entry.get('flags'):
            lines.append('      flags = { ' + ', '.join(lua_quote(flag) for flag in sorted(entry['flags'])) + ' },')
        lines.append('    },')
    lines.extend(['  },', '}', ''])
    return '\n'.join(lines)


def _is_generated_catalog(path: Path) -> bool:
    """Only our own generated files may be removed from an output directory."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        with path.open('r', encoding='utf-8') as stream:
            return stream.readline().rstrip('\r\n') == GENERATED_HEADER
    except (OSError, UnicodeDecodeError):
        return False


def build(po_dir: Path, output: Path, glossary: Path | None = None) -> list[Path]:
    check(po_dir, glossary)
    output.mkdir(parents=True, exist_ok=True)
    rendered: list[tuple[Path, str]] = []
    for path in sorted(po_dir.glob('*.po'), key=lambda item: item.name):
        entries, headers = parse_po(path)
        target = output / (path.stem + '.lua')
        rendered.append((target, render_catalog(path.stem, entries, headers, path.name)))

    # Preflight every destination before the first write: an existing target is
    # safe to replace only when it is one of our own regular generated files.
    for target, _ in rendered:
        if (target.exists() or target.is_symlink()) and not _is_generated_catalog(target):
            raise CatalogError(f'{target}: refusing to overwrite a non-generated file or symlink')

    # Finish every parse/render before publishing anything. Each target is then
    # replaced atomically, and stale cleanup happens only after all writes work.
    for target, text in rendered:
        atomic_write_text(target, text)
    expected = {target.name for target, _ in rendered}
    for stale in output.glob('*.lua'):
        if stale.name not in expected and _is_generated_catalog(stale):
            stale.unlink()
    return [target for target, _ in rendered]



def compare_sync(before: dict, after: dict) -> list[dict]:
    """Compare two untrusted offline snapshots without modifying either side."""
    if not isinstance(before, dict) or not isinstance(after, dict):
        raise CatalogError('sync snapshots must be JSON objects')
    report: list[dict] = []
    old_sources = before.get('sources', {})
    new_sources = after.get('sources', {})
    if not isinstance(old_sources, dict) or not isinstance(new_sources, dict):
        raise CatalogError('sync snapshot sources must be objects')
    for source in sorted(set(old_sources) | set(new_sources)):
        old = old_sources.get(source, {}).get('sha256')
        new = new_sources.get(source, {}).get('sha256')
        if old is None:
            report.append({'kind': 'source_added', 'source': source, 'sha256': new})
        elif new is None:
            report.append({'kind': 'source_removed', 'source': source, 'sha256': old})
        elif old != new:
            report.append({'kind': 'source_changed', 'source': source, 'before': old, 'after': new})

    def entries(snapshot: dict) -> list[dict]:
        value = snapshot.get('entries', [])
        if not isinstance(value, list):
            raise CatalogError('sync snapshot entries must be an array')
        for entry in value:
            if not isinstance(entry, dict) or not isinstance(entry.get('msgid'), str):
                raise CatalogError('sync entries require string msgid')
        return value

    old_entries, new_entries = entries(before), entries(after)
    old_map = {(entry.get('context', ''), entry['msgid']): entry for entry in old_entries}
    new_map = {(entry.get('context', ''), entry['msgid']): entry for entry in new_entries}
    removed = {key: entry for key, entry in old_map.items() if key not in new_map}
    added = {key: entry for key, entry in new_map.items() if key not in old_map}
    paired_old: set[tuple[str, str]] = set()
    paired_new: set[tuple[str, str]] = set()
    for old_key, old_entry in sorted(removed.items()):
        for new_key, new_entry in sorted(added.items()):
            if new_key in paired_new or old_key[0] != new_key[0]:
                continue
            if old_entry.get('msgstr') and old_entry.get('msgstr') == new_entry.get('msgstr'):
                report.append({'kind': 'msgid_changed', 'context': old_key[0], 'msgid': old_key[1], 'new_msgid': new_key[1]})
                paired_old.add(old_key)
                paired_new.add(new_key)
                break
    for key in sorted(removed):
        if key not in paired_old:
            report.append({'kind': 'entry_removed', 'context': key[0], 'msgid': key[1]})
    for key in sorted(added):
        if key not in paired_new:
            report.append({'kind': 'entry_added', 'context': key[0], 'msgid': key[1]})
    for entry in new_entries:
        if not entry.get('msgstr'):
            report.append({'kind': 'untranslated', 'context': entry.get('context', ''), 'msgid': entry['msgid']})
        references = entry.get('references', [])
        if any(report_item['kind'] == 'source_changed' and report_item['source'] in references
               for report_item in report):
            report.append({'kind': 'possibly_stale', 'context': entry.get('context', ''), 'msgid': entry['msgid']})
    return report


def release_check(root: Path) -> list[str]:
    """Return release-blocking paths; never edits the candidate tree."""
    problems: list[str] = []
    forbidden_parts = {'__pycache__', '.pytest_cache', '.cache', 'node_modules', '.git', '.agents', '.codex', '.aws'}
    forbidden_suffixes = {'.pyc', '.pyo', '.log', '.tmp', '.bak', '.swp', '.zip', '.gz'}
    # Neovim 0.10/0.11 fall back to ./.nvimlog (and 0.12 to ./nvim.log) when the
    # state directory is read-only. Path('.nvimlog').suffix is '' for a leading
    # dot, so the suffix rule alone lets this one through.
    forbidden_names = {'.nvimlog'}
    for path in sorted(root.rglob('*')):
        relative = path.relative_to(root)
        if any(part in forbidden_parts for part in relative.parts):
            problems.append(f'cache/vcs path: {relative}')
            continue
        lower = path.name.lower()
        if any(token in lower for token in ('backup-', '.bak-before-', '.kiss-backup-', '.pristine', '.patched')):
            problems.append(f'scattered backup: {relative}')
        if path.is_symlink():
            problems.append(f'symlink requires review: {relative}')
        elif path.is_file():
            if path.stat().st_size == 0:
                problems.append(f'zero-byte file: {relative}')
            if path.suffix.lower() in forbidden_suffixes or lower in forbidden_names:
                problems.append(f'temporary/log/archive file: {relative}')
            if relative.parts[:2] in (('research', 'downloads'), ('research', 'upstream')):
                problems.append(f'research download: {relative}')
    return sorted(set(problems))


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def manifest_snapshot(manifest: dict) -> dict:
    sources = {}
    for upstream in manifest.get('upstreams', {}).values():
        sources.update(upstream.get('sources', {}))
        for meta in upstream.get('documents', {}).values():
            sources[meta['source']] = {'sha256': meta['sha256']}
    return {'sources': sources, 'entries': []}


def local_manifest_snapshot(manifest: dict, source_root: Path) -> dict:
    result = {'sources': {}, 'entries': []}
    for name, upstream in manifest.get('upstreams', {}).items():
        for source in upstream.get('sources', {}):
            path = source_root / name / source
            if path.is_file():
                result['sources'][source] = {'sha256': _sha256(path)}
        for document, meta in upstream.get('documents', {}).items():
            path = source_root / name / meta['source']
            if path.is_file():
                result['sources'][meta['source']] = {'sha256': _sha256(path)}
    return result


def fetched_manifest_snapshot(manifest: dict) -> dict:
    result = {'sources': {}, 'entries': []}
    for name, upstream in manifest.get('upstreams', {}).items():
        repository = upstream.get('repository', '')
        prefix = 'https://github.com/'
        if not repository.startswith(prefix):
            raise CatalogError(f'{name}: only explicit GitHub upstream URLs are supported')
        repo = repository[len(prefix):].strip('/')
        commit = upstream['commit']
        paths = dict(upstream.get('sources', {}))
        for meta in upstream.get('documents', {}).values():
            paths[meta['source']] = meta
        for source in sorted(paths):
            url = f'https://raw.githubusercontent.com/{repo}/{commit}/{source}'
            try:
                with urllib.request.urlopen(url, timeout=30) as response:
                    digest = hashlib.sha256(response.read()).hexdigest()
            except Exception as exc:
                raise CatalogError(f'{name}:{source}: fetch failed: {exc}') from exc
            result['sources'][source] = {'sha256': digest}
    return result


def main(argv: list[str] | None = None) -> int:
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('check', 'build', 'sync', 'release-check'))
    parser.add_argument('--po-dir', type=Path, default=root / 'translations/po/zh_CN')
    parser.add_argument('--glossary', type=Path, default=root / 'translations/glossary/zh_CN.toml')
    parser.add_argument('--output', type=Path, default=root / 'lua/nvim-zh/catalogs/generated')
    parser.add_argument('--fixture', type=Path, help='offline sync JSON containing before/after snapshots')
    parser.add_argument('--source-root', type=Path, help='offline directory containing named upstream checkouts')
    parser.add_argument('--fetch', action='store_true', help='explicitly fetch pinned upstream sources read-only')
    parser.add_argument('--manifest', type=Path, default=root / 'manifests/upstreams.json')
    parser.add_argument('--package-dir', type=Path, default=root)
    args = parser.parse_args(argv)
    try:
        if args.command in ('check', 'build') and args.po_dir.resolve() == (root / 'translations/po/zh_CN').resolve():
            builtin_sources(root)
        if args.command == 'check':
            result = check(args.po_dir, args.glossary)
            print(f'CATALOG_CHECK=PASS domains={result["domains"]} entries={result["entries"]}')
        elif args.command == 'build':
            files = build(args.po_dir, args.output, args.glossary)
            print(f'CATALOG_BUILD=PASS files={len(files)} output={args.output}')
        elif args.command == 'release-check':
            problems = release_check(args.package_dir)
            for problem in problems:
                print(f'RELEASE_ERROR={problem}', file=sys.stderr)
            if problems:
                return 1
            files = sum(1 for path in args.package_dir.rglob('*') if path.is_file())
            print(f'RELEASE_CHECK=PASS files={files} package={args.package_dir}')
        else:
            manifest = json.loads(args.manifest.read_text(encoding='utf-8'))
            before = manifest_snapshot(manifest)
            if args.fixture:
                fixture = json.loads(args.fixture.read_text(encoding='utf-8'))
                before, after = fixture['before'], fixture['after']
            elif args.source_root:
                after = local_manifest_snapshot(manifest, args.source_root)
            elif args.fetch:
                after = fetched_manifest_snapshot(manifest)
            else:
                after = before
            report = compare_sync(before, after)
            labels = {'source_changed': 'UPSTREAM_CHANGE', 'source_added': 'UPSTREAM_CHANGE', 'source_removed': 'UPSTREAM_CHANGE',
                      'entry_added': 'UPSTREAM_CHANGE', 'entry_removed': 'UPSTREAM_CHANGE', 'msgid_changed': 'UPSTREAM_CHANGE',
                      'possibly_stale': 'STALE_TRANSLATION', 'untranslated': 'UNTRANSLATED'}
            for item in report:
                detail = ':'.join(str(item.get(key, '')) for key in ('source', 'context', 'msgid', 'new_msgid') if item.get(key) is not None)
                print(f'{labels[item["kind"]]}={item["kind"]}:{detail}')
            print(f'SYNC_STATUS={"CHANGES" if report else "OK"} changes={len(report)} network={str(args.fetch).lower()}')
    except CatalogError as exc:
        print(f'CATALOG_ERROR={exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
